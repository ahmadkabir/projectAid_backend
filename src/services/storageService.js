import fs from 'fs';
import fsp from 'fs/promises';
import path from 'path';
import crypto from 'crypto';
import { fileURLToPath } from 'url';
import {
  S3Client,
  PutObjectCommand,
  GetObjectCommand,
  HeadObjectCommand,
  DeleteObjectCommand
} from '@aws-sdk/client-s3';
import { getSignedUrl } from '@aws-sdk/s3-request-presigner';

/**
 * Storage abstraction for project files.
 *
 * Two providers are supported:
 *  - `local` (default): files are written under `uploads/private/...`, which is
 *    NOT served statically. They can only leave the server through the
 *    authenticated download endpoint.
 *  - `s3`: any S3-compatible object store (AWS S3, Cloudflare R2, MinIO…).
 *    Objects are private; uploads and downloads use short-lived presigned URLs
 *    generated by the official AWS SDK, so credentials never reach the browser.
 *
 * Configuration (backend/.env):
 *   STORAGE_PROVIDER=local|s3   (default: local)
 *   STORAGE_S3_ENDPOINT, STORAGE_S3_REGION, STORAGE_S3_BUCKET,
 *   STORAGE_S3_ACCESS_KEY_ID, STORAGE_S3_SECRET_ACCESS_KEY,
 *   STORAGE_S3_FORCE_PATH_STYLE (default true), STORAGE_PREFIX
 *   STORAGE_DOWNLOAD_URL_TTL (seconds, default 300)
 *   STORAGE_UPLOAD_URL_TTL   (seconds, default 900)
 *
 * Cloudflare R2 aliases are also accepted: R2_ENDPOINT, R2_BUCKET_NAME,
 * R2_ACCESS_KEY_ID, R2_SECRET_ACCESS_KEY. With R2 the region must be `auto`
 * and path style addressing must stay enabled.
 */

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const backendRoot = path.resolve(__dirname, '../..');

export const uploadsRoot = path.resolve(backendRoot, process.env.UPLOAD_DIR || 'uploads');

const ALLOWED_CATEGORIES = ['documentation', 'software', 'guide'];

const firstValue = (...values) => {
  for (const value of values) {
    if (value !== undefined && value !== null && String(value).trim() !== '') {
      return String(value).trim();
    }
  }
  return '';
};

const getS3Config = () => ({
  endpoint: firstValue(process.env.STORAGE_S3_ENDPOINT, process.env.R2_ENDPOINT).replace(/\/+$/, ''),
  region: firstValue(process.env.STORAGE_S3_REGION) || 'auto',
  bucket: firstValue(process.env.STORAGE_S3_BUCKET, process.env.R2_BUCKET_NAME),
  accessKeyId: firstValue(process.env.STORAGE_S3_ACCESS_KEY_ID, process.env.R2_ACCESS_KEY_ID),
  secretAccessKey: firstValue(
    process.env.STORAGE_S3_SECRET_ACCESS_KEY,
    process.env.R2_SECRET_ACCESS_KEY
  ),
  forcePathStyle: (process.env.STORAGE_S3_FORCE_PATH_STYLE || 'true') !== 'false'
});

const r2Configured = () => {
  const cfg = getS3Config();
  return Boolean(cfg.endpoint && cfg.bucket && cfg.accessKeyId && cfg.secretAccessKey);
};

/**
 * Resolve the provider on every call so a `.env` change is picked up without
 * code changes. Object storage is opt-in via STORAGE_PROVIDER=s3: silently
 * switching to R2 would make an upload fail whenever the bucket credentials
 * are missing or wrong.
 */
export const getStorageProvider = () => {
  const explicit = String(process.env.STORAGE_PROVIDER || '').trim().toLowerCase();
  return explicit === 's3' ? 's3' : 'local';
};

const getPrefix = () => String(process.env.STORAGE_PREFIX || '').replace(/^\/+|\/+$/g, '');

export const isStorageConfigured = () => {
  if (getStorageProvider() !== 's3') return true;
  return r2Configured();
};

/** Lowercase extension including the dot, or '' when there is none. */
export const extensionOf = (fileName = '') => {
  const ext = path.extname(String(fileName)).toLowerCase();
  return /^\.[a-z0-9]{1,8}$/.test(ext) ? ext : '';
};

/**
 * Sanitise a browser supplied file name for display only. Never used to build
 * a storage path.
 */
export const sanitizeFileName = (fileName = '') => {
  return String(fileName)
    .replace(/[\u0000-\u001f\u007f]/g, '')
    .replace(/[\\/]+/g, '-')
    .replace(/\s+/g, ' ')
    .trim()
    .slice(0, 255) || 'file';
};

/**
 * Build an unguessable storage key. Keys never contain user supplied paths.
 */
export const buildStorageKey = ({ category, projectId, originalName }) => {
  if (!ALLOWED_CATEGORIES.includes(category)) {
    throw new Error(`Unsupported file category: ${category}`);
  }
  const ext = extensionOf(originalName);
  const unique = `${Date.now()}-${crypto.randomBytes(12).toString('hex')}`;
  const prefix = getPrefix() ? `${getPrefix()}/` : '';
  return `${prefix}${category}/${projectId}/${unique}${ext}`;
};

/** True when a key belongs to the given category/project namespace. */
export const isKeyInNamespace = (key, { category, projectId }) => {
  if (!ALLOWED_CATEGORIES.includes(category)) return false;
  if (typeof key !== 'string' || key.includes('\\')) return false;
  if (key.split('/').some((segment) => segment === '' || segment === '.' || segment === '..')) {
    return false;
  }
  const prefix = getPrefix() ? `${getPrefix()}/` : '';
  const expected = `${prefix}${category}/${projectId}/`;
  return key.startsWith(expected);
};

export const checksumOf = (buffer) => crypto.createHash('sha256').update(buffer).digest('hex');

const normalizeLocalKey = (key) => String(key || '').replace(/^\/+/, '').replace(/^uploads\//, '');

export const localPathForKey = (key) => {
  const resolved = path.resolve(uploadsRoot, normalizeLocalKey(key));
  if (!resolved.startsWith(uploadsRoot + path.sep) && resolved !== uploadsRoot) {
    throw new Error('Invalid storage key');
  }
  return resolved;
};

/** The `uploads/...` path stored in the legacy filePath column. */
export const legacyPathForKey = (key) => `uploads/${normalizeLocalKey(key)}`;

// ---------------------------------------------------------------------------
// Local provider
// ---------------------------------------------------------------------------

const saveLocal = async (key, buffer) => {
  const target = localPathForKey(key);
  await fsp.mkdir(path.dirname(target), { recursive: true });
  // Write to a temp file then rename so a crash cannot leave a partial object.
  const tmp = `${target}.${crypto.randomBytes(4).toString('hex')}.part`;
  await fsp.writeFile(tmp, buffer);
  await fsp.rename(tmp, target);
};

const readLocal = async (key) => fsp.readFile(localPathForKey(key));

const statLocal = async (key) => {
  try {
    return await fsp.stat(localPathForKey(key));
  } catch {
    return null;
  }
};

const deleteLocal = async (key) => {
  try {
    await fsp.unlink(localPathForKey(key));
    return true;
  } catch (error) {
    if (error.code === 'ENOENT') return false;
    throw error;
  }
};

// ---------------------------------------------------------------------------
// S3-compatible provider (AWS SDK v3 — Cloudflare R2 compatible)
// ---------------------------------------------------------------------------

let cachedClient = null;
let cachedSignature = '';

const getS3Client = () => {
  const cfg = getS3Config();
  if (!cfg.endpoint || !cfg.bucket || !cfg.accessKeyId || !cfg.secretAccessKey) {
    throw new Error(
      'Object storage is not configured (set R2_ENDPOINT / R2_BUCKET_NAME / R2_ACCESS_KEY_ID / R2_SECRET_ACCESS_KEY)'
    );
  }

  const signature = JSON.stringify([cfg.endpoint, cfg.region, cfg.bucket, cfg.accessKeyId, cfg.forcePathStyle]);
  if (cachedClient && signature === cachedSignature) return cachedClient;

  cachedClient = new S3Client({
    region: cfg.region,
    endpoint: cfg.endpoint,
    forcePathStyle: cfg.forcePathStyle,
    credentials: {
      accessKeyId: cfg.accessKeyId,
      secretAccessKey: cfg.secretAccessKey
    },
    // R2 rejects the automatic CRC32 checksum headers recent SDK versions add
    // to presigned PUTs unless the browser mirrors them. Sign on demand only.
    requestChecksumCalculation: 'WHEN_REQUIRED',
    responseChecksumValidation: 'WHEN_REQUIRED'
  });
  cachedSignature = signature;
  return cachedClient;
};

const objectError = (action, error) => {
  const status = error?.$metadata?.httpStatusCode;
  const message = new Error(
    `Object storage ${action} failed${status ? ` (${status})` : ''}: ${error?.message || 'unknown error'}`
  );
  message.name = error?.name || 'ObjectStorageError';
  message.cause = error;
  return message;
};

const isNotFound = (error) =>
  error?.name === 'NotFound' ||
  error?.name === 'NoSuchKey' ||
  error?.$metadata?.httpStatusCode === 404;

// ---------------------------------------------------------------------------
// Public API
// ---------------------------------------------------------------------------

/**
 * Persist a buffer. Returns the metadata needed to record the file.
 */
export const saveBuffer = async (key, buffer, { contentType } = {}) => {
  if (!Buffer.isBuffer(buffer)) {
    throw new Error('saveBuffer expects a Buffer');
  }

  if (getStorageProvider() === 's3') {
    const cfg = getS3Config();
    try {
      await getS3Client().send(
        new PutObjectCommand({
          Bucket: cfg.bucket,
          Key: key,
          Body: buffer,
          ContentType: contentType || undefined
        })
      );
    } catch (error) {
      throw objectError('PUT', error);
    }
  } else {
    await saveLocal(key, buffer);
  }

  return {
    key,
    provider: getStorageProvider(),
    size: buffer.length,
    checksum: checksumOf(buffer),
    mimeType: contentType || null
  };
};

export const readBuffer = async (key) => {
  if (getStorageProvider() === 's3') {
    const cfg = getS3Config();
    try {
      const response = await getS3Client().send(
        new GetObjectCommand({ Bucket: cfg.bucket, Key: key })
      );
      return Buffer.from(await response.Body.transformToByteArray());
    } catch (error) {
      throw objectError('GET', error);
    }
  }
  return readLocal(key);
};

/**
 * Read the first `bytes` of an object without downloading it entirely. Used to
 * verify the real file signature of a direct browser upload.
 */
export const readObjectPrefix = async (key, bytes = 65536) => {
  const size = Math.max(1, Math.min(Number(bytes) || 65536, 5 * 1024 * 1024));

  if (getStorageProvider() === 's3') {
    const cfg = getS3Config();
    try {
      const response = await getS3Client().send(
        new GetObjectCommand({
          Bucket: cfg.bucket,
          Key: key,
          Range: `bytes=0-${size - 1}`
        })
      );
      return Buffer.from(await response.Body.transformToByteArray());
    } catch (error) {
      throw objectError('Range GET', error);
    }
  }

  const handle = await fsp.open(localPathForKey(key), 'r');
  try {
    const buffer = Buffer.alloc(size);
    const { bytesRead } = await handle.read(buffer, 0, size, 0);
    return buffer.subarray(0, bytesRead);
  } finally {
    await handle.close();
  }
};

export const statObject = async (key) => {
  if (getStorageProvider() === 's3') {
    const cfg = getS3Config();
    try {
      const response = await getS3Client().send(
        new HeadObjectCommand({ Bucket: cfg.bucket, Key: key })
      );
      const stat = {
        exists: true,
        size: Number(response.ContentLength) || 0,
        etag: response.ETag || null
      };
      if (response.ContentType) stat.contentType = response.ContentType;
      return stat;
    } catch (error) {
      if (isNotFound(error)) return null;
      throw objectError('HEAD', error);
    }
  }

  const stat = await statLocal(key);
  return stat ? { exists: true, size: stat.size } : null;
};

export const deleteObject = async (key) => {
  if (!key) return false;

  if (getStorageProvider() === 's3') {
    const cfg = getS3Config();
    try {
      await getS3Client().send(new DeleteObjectCommand({ Bucket: cfg.bucket, Key: key }));
      return true;
    } catch (error) {
      if (isNotFound(error)) return false;
      throw objectError('DELETE', error);
    }
  }

  return deleteLocal(key);
};

export const createReadStream = (key) => {
  if (getStorageProvider() === 's3') {
    throw new Error('Streaming is only available for the local provider');
  }
  return fs.createReadStream(localPathForKey(key));
};

/**
 * Short-lived download URL for providers that support it. Returns null for the
 * local provider, where the backend streams the file instead.
 */
export const getSignedDownloadUrl = async (key, { expiresIn } = {}) => {
  if (getStorageProvider() !== 's3') return null;

  const cfg = getS3Config();
  const ttl = Number(expiresIn || process.env.STORAGE_DOWNLOAD_URL_TTL || 300);

  return getSignedUrl(
    getS3Client(),
    new GetObjectCommand({ Bucket: cfg.bucket, Key: key }),
    { expiresIn: Math.max(30, Math.min(ttl, 3600)) }
  );
};

/**
 * Short-lived URL that lets an authenticated admin PUT one object directly to
 * R2. The object stays private; the browser only receives this scoped URL.
 *
 * The returned headers must be sent verbatim with the PUT, otherwise the
 * signature will not match.
 */
export const getSignedUploadUrl = async (key, { contentType, expiresIn } = {}) => {
  if (getStorageProvider() !== 's3') {
    throw new Error('Direct uploads require the s3 storage provider');
  }

  const cfg = getS3Config();
  const ttl = Number(expiresIn || process.env.STORAGE_UPLOAD_URL_TTL || 900);
  const command = new PutObjectCommand({
    Bucket: cfg.bucket,
    Key: key,
    ContentType: contentType || undefined
  });

  const url = await getSignedUrl(getS3Client(), command, {
    expiresIn: Math.max(60, Math.min(ttl, 3600))
  });

  return {
    url,
    headers: contentType ? { 'Content-Type': contentType } : {},
    expiresIn: Math.max(60, Math.min(ttl, 3600))
  };
};

